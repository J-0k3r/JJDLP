# 手机号识别与脱敏
import re

CHINA_MOBILE_PREFIXES = set([
    # 中国移动
    '134', '135', '136', '137', '138', '139',
    '147', '148',
    '150', '151', '152', '157', '158', '159',
    '178', '182', '183', '184', '187', '188',
    '198', '195', '197', '199',

    # 中国联通
    '130', '131', '132',
    '145', '146',
    '155', '156',
    '166', '167',
    '171', '175', '176',
    '185', '186',
    '196',

    # 中国电信
    '133', '149', '153',
    '170', '173', '174',  # 注意：170需配合第4位判断，但简单场景可保留
    '180', '181', '189',
    '190', '191', '193', '199',  # 199 与移动共用

    # 中国广电
    '192'
])

def is_phone(text: str) -> bool:
    """
    只识别中国大陆11位手机号+常见号段
    """
    if not (isinstance(text, str) and len(text) == 11 and text.isdigit()):
        return False
    return text[:3] in CHINA_MOBILE_PREFIXES

def mask_phone(text: str) -> str:
    """
    手机号脱敏：前3后4，中间四位*。
    """
    if is_phone(text):
        return text[:3] + '****' + text[-4:]
    return text

